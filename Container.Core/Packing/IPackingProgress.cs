namespace Container_V3.Packing;

/// <summary>
/// Прогресс упаковывания для того, кто упаковку вызвал: панель Total Commander (её
/// tProcessDataProc из SetProcessDataProc), командная строка, любой другой вызывающий.
///
/// Вызов происходит после того, как последний фрагмент файла записан в контейнер, то есть ровно
/// один раз на файл и в том же порядке, в каком файлы легли в чанки. Такой порядок выбран
/// специально: панель показывает прогресс по файлам, а не по чанкам, и «файл готов» — единственная
/// граница, которая имеет смысл для пользователя.
///
/// Возврат false означает «прекращай»: вызывающий сообщил, что операцию остановили (в TC это
/// нажатие Stop в диалоге прогресса). Упаковщик в ответ прекращает дописывать чанки и поднимает
/// PackingAbortedException; индекс при этом не переписывается, а уже дописанные в конец чанты
/// отсекаются — контейнер остаётся ровно таким, каким был до начала операции, побайтово.
/// </summary>
public interface IPackingProgress
{
    /// <summary>Файл записан целиком: sourceFullPath — путь на диске, uncompressedBytes — его размер до сжатия.</summary>
    bool FilePacked(string sourceFullPath, long uncompressedBytes);
}
